-- A mentee must not be able to reassign mentors, programs, or her own phase.
drop policy if exists "update enrollments" on public.enrollments;
create policy "mentors and admins update enrollments" on public.enrollments
  for update to authenticated
  using (mentor_id = auth.uid() or public.is_admin())
  with check (mentor_id = auth.uid() or public.is_admin());

grant insert, update, delete on public.meetings to authenticated;
drop policy if exists "mentors manage meetings" on public.meetings;
create policy "mentors manage meetings" on public.meetings for all to authenticated
  using (
    public.is_admin()
    or (enrollment_id is not null and exists (
      select 1 from public.enrollments e
       where e.id = enrollment_id and e.mentor_id = auth.uid()
    ))
  )
  with check (
    public.is_admin()
    or (enrollment_id is not null and exists (
      select 1 from public.enrollments e
       where e.id = enrollment_id and e.mentor_id = auth.uid()
    ))
  );

-- Audit rows are generated by trusted database triggers, never supplied by the browser.
revoke insert on public.audit_log from authenticated;
drop policy if exists "insert audit" on public.audit_log;

create or replace function public.audit_sensitive_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.audit_log (actor_id, action, target, payload)
  values (
    auth.uid(),
    tg_op || '_' || tg_table_name,
    coalesce(to_jsonb(new) ->> 'id', to_jsonb(old) ->> 'id'),
    jsonb_build_object(
      'before', case when tg_op <> 'INSERT' then to_jsonb(old) else null end,
      'after', case when tg_op <> 'DELETE' then to_jsonb(new) else null end
    )
  );
  return coalesce(new, old);
end;
$$;

revoke all on function public.audit_sensitive_change() from public, anon, authenticated;

drop trigger if exists audit_allowed_emails on public.allowed_emails;
create trigger audit_allowed_emails
  after insert or update or delete on public.allowed_emails
  for each row execute function public.audit_sensitive_change();

drop trigger if exists audit_user_roles on public.user_roles;
create trigger audit_user_roles
  after insert or update or delete on public.user_roles
  for each row execute function public.audit_sensitive_change();

-- One private bucket. Paths start with the profile UUID:
-- <owner-profile-id>/<area>/<random-file-name>
insert into storage.buckets (id, name, public, file_size_limit)
values ('rise-private', 'rise-private', false, 52428800)
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit;

drop policy if exists "rise private read" on storage.objects;
create policy "rise private read" on storage.objects for select to authenticated
  using (
    bucket_id = 'rise-private'
    and (
      (storage.foldername(name))[1] = auth.uid()::text
      or public.is_admin()
      or exists (
        select 1 from public.enrollments e
         where e.mentor_id = auth.uid()
           and e.mentee_id::text = (storage.foldername(name))[1]
      )
    )
  );

drop policy if exists "rise private insert" on storage.objects;
create policy "rise private insert" on storage.objects for insert to authenticated
  with check (
    bucket_id = 'rise-private'
    and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
  );

drop policy if exists "rise private update" on storage.objects;
create policy "rise private update" on storage.objects for update to authenticated
  using (
    bucket_id = 'rise-private'
    and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
  )
  with check (
    bucket_id = 'rise-private'
    and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
  );

drop policy if exists "rise private delete" on storage.objects;
create policy "rise private delete" on storage.objects for delete to authenticated
  using (
    bucket_id = 'rise-private'
    and ((storage.foldername(name))[1] = auth.uid()::text or public.is_admin())
  );
