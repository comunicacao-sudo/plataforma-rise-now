-- RISE NOW security hardening
-- Apply through Lovable Cloud / Supabase SQL after reviewing in the target environment.

-- Normalize invitations so mixed-case addresses cannot bypass uniqueness checks.
update public.allowed_emails set email = lower(trim(email));
update public.profiles set email = lower(trim(email));

create unique index if not exists allowed_emails_lower_email_idx
  on public.allowed_emails (lower(email));

-- An auth user may only be created when an active invitation exists. The trigger
-- also binds the public profile id to auth.uid(), which is required by every RLS policy.
create or replace function public.claim_approved_invitation()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  approved_invite public.allowed_emails%rowtype;
  profile_name text;
begin
  select *
    into approved_invite
    from public.allowed_emails
   where lower(email) = lower(new.email)
     and status = 'approved'
   limit 1;

  if approved_invite.id is null then
    raise exception using
      errcode = '42501',
      message = 'RISE_ACCESS_NOT_APPROVED';
  end if;

  profile_name := coalesce(
    nullif(approved_invite.full_name, ''),
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    split_part(new.email, '@', 1)
  );

  insert into public.profiles (id, email, full_name, claimed)
  values (new.id, lower(new.email), profile_name, true)
  on conflict (email) do update
    set id = excluded.id,
        full_name = excluded.full_name,
        claimed = true;

  insert into public.user_roles (user_id, role)
  values (new.id, approved_invite.role)
  on conflict (user_id, role) do nothing;

  return new;
end;
$$;

revoke all on function public.claim_approved_invitation() from public, anon, authenticated;

drop trigger if exists on_rise_user_created on auth.users;
create trigger on_rise_user_created
  after insert on auth.users
  for each row execute function public.claim_approved_invitation();

-- Profile fields that influence authorization are never client-editable.
revoke update on public.profiles from authenticated;
grant update (full_name, title, avatar_url) on public.profiles to authenticated;

-- Administrators can maintain roles and program content. The browser still
-- cannot grant itself admin because the policy checks the existing DB role.
grant insert, update, delete on public.user_roles to authenticated;
drop policy if exists "admins manage roles" on public.user_roles;
create policy "admins manage roles" on public.user_roles for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

grant insert, update, delete on public.programs to authenticated;
grant insert, update, delete on public.phases to authenticated;
grant insert, update, delete on public.lessons to authenticated;
grant insert, update, delete on public.deliverables to authenticated;

drop policy if exists "admins manage programs" on public.programs;
create policy "admins manage programs" on public.programs for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admins manage phases" on public.phases;
create policy "admins manage phases" on public.phases for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admins manage lessons" on public.lessons;
create policy "admins manage lessons" on public.lessons for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admins manage deliverables" on public.deliverables;
